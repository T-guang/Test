        private static CommonFormulaEntry Formula(string id, string title, string category, string shortDescription, string[] expressions, string[] variants, string variables, string unitDescription, string useCase, string example, string commonMistakes, string note, params string[] aliases)
        {
            return new CommonFormulaEntry
            {
                Id = id,
                Title = title,
                Category = category,
                ShortDescription = shortDescription,
                Expression = expressions != null && expressions.Length > 0 ? expressions[0] : string.Empty,
                Expressions = expressions != null ? new List<string>(expressions) : new List<string>(),
                Variants = variants != null ? new List<string>(variants) : new List<string>(),
                Variables = variables,
                UnitDescription = unitDescription,
                UseCase = useCase,
                Example = example,
                CommonMistakes = commonMistakes,
                Note = note,
                Aliases = aliases
            };
        }

        private static CommonArticleEntry Article(string id, string title, string category, string learningGoal, string keyPoints, string commonMistakes, string relationToSystem, ArticleSection[] sections, params string[] aliases)
        {
            return new CommonArticleEntry
            {
                Id = id,
                Title = title,
                Category = category,
                LearningGoal = learningGoal,
                Content = sections != null && sections.Length > 0 ? sections[0].Body : string.Empty,
                Sections = sections != null ? new List<ArticleSection>(sections) : new List<ArticleSection>(),
                KeyPoints = keyPoints,
                CommonMistakes = commonMistakes,
                RelationToSystem = relationToSystem,
                Aliases = aliases
            };
        }

